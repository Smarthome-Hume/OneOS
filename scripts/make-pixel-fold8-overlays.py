#!/usr/bin/env python3
"""Rebuild the small, guest-only Fold8 Pixel configuration in guest_prepare.sh.

Requires Android SDK build tools, a platform android.jar, Java and a debug
keystore. No donor APK or system image is needed. The generated signed APKs
contain resources only, and are compressed into the integrity-checked startup
script so existing OneOS staging/app schemas need no new package-set files.
"""
import argparse
import base64
import gzip
import hashlib
import os
from pathlib import Path
import subprocess
import tempfile
import textwrap

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '# BEGIN GENERATED PIXEL FOLD8 CONFIG'
END = '# END GENERATED PIXEL FOLD8 CONFIG'


def run(*args):
    subprocess.run([str(a) for a in args], check=True, capture_output=True)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--sdk', type=Path, default=Path(os.environ.get('ANDROID_HOME', Path.home() / 'Library/Android/sdk')))
    p.add_argument('--build-tools', default='36.0.0')
    p.add_argument('--platform', default='android-37.0')
    p.add_argument('--keystore', type=Path, default=Path.home() / '.android/debug.keystore')
    a = p.parse_args()
    bt = a.sdk / 'build-tools' / a.build_tools
    jar = a.sdk / 'platforms' / a.platform / 'android.jar'
    for f in (bt / 'aapt2', bt / 'zipalign', bt / 'apksigner', jar, a.keystore):
        if not f.is_file():
            p.error(f'Missing {f}; provide the SDK, platform and debug keystore paths')
    script = ROOT / 'switcher/assets/guest_prepare.sh'
    source = script.read_text()
    assert source.count(BEGIN) == source.count(END) == 1
    lines = [BEGIN, '# Generated by scripts/make-pixel-fold8-overlays.py from switcher/overlays/pixel_fold8_*.',
             '# Immutable boot resources let system_server see AOD and retain bar geometry.',
             '# Native clock/icon dimensions and the user AOD setting are not overridden.',
             'if [ "${ONEOS_PROFILE:-}" = f8 ] && [ -f "$GUEST_SYSTEM_EXT/priv-app/SystemUIGoogle/SystemUIGoogle.apk" ] && [ ! -f "$ROOTFS/system/framework/oplus-services.jar" ]; then',
             '    mkdir -p "$STAGE/oem/overlay"']
    with tempfile.TemporaryDirectory(prefix='pixel-fold8-') as temp:
        for kind in ('framework', 'systemui'):
            w = Path(temp) / kind
            w.mkdir()
            src = ROOT / 'switcher/overlays' / ('pixel_fold8_' + kind)
            run(bt / 'aapt2', 'compile', '--dir', src / 'res', '-o', w / 'compiled.zip')
            run(bt / 'aapt2', 'link', '-o', w / 'unsigned.apk', '--manifest', src / 'AndroidManifest.xml',
                '-I', jar, '--min-sdk-version', '31', '--target-sdk-version', '36', '--auto-add-overlay', w / 'compiled.zip')
            run(bt / 'zipalign', '-f', '4', w / 'unsigned.apk', w / 'aligned.apk')
            run(bt / 'apksigner', 'sign', '--ks', a.keystore, '--ks-key-alias', 'androiddebugkey',
                '--ks-pass', 'pass:android', '--key-pass', 'pass:android', '--out', w / 'overlay.apk', w / 'aligned.apk')
            data = (w / 'overlay.apk').read_bytes()
            filename = 'OneOSPixelFold8' + kind.title() + '.apk'
            marker = 'ONEOS_PIXEL_FOLD8_' + kind.upper()
            lines += [f'    "$BB" base64 -d <<\'{marker}\' | "$BB" gzip -d > "$STAGE/oem/overlay/{filename}"',
                      textwrap.fill(base64.b64encode(gzip.compress(data, mtime=0)).decode(), 76), marker,
                      f'    [ "$(sha256sum "$STAGE/oem/overlay/{filename}" | cut -d \' \' -f 1)" = "{hashlib.sha256(data).hexdigest()}" ] || {{ echo "ERROR: Pixel Fold8 overlay checksum"; exit 3; }}',
                      f'    chmod 644 "$STAGE/oem/overlay/{filename}"',
                      f'    OEM_FILES="$OEM_FILES overlay/{filename}"']
    lines += ['    echo "Pixel Fold8: immutable AOD and status-bar configuration staged"', 'fi', END]
    start, stop = source.index(BEGIN), source.index(END) + len(END)
    script.write_text(source[:start] + '\n'.join(lines) + source[stop:])
    print(f'Updated {script.relative_to(ROOT)}; only Fold8 Pixel guest resources are staged')


if __name__ == '__main__':
    main()
